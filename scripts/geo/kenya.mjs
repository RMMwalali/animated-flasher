// Generates src/components/destinations/kenya.ts: Kenya's outline (Natural
// Earth 1:10m via world-atlas, public domain) as an SVG path in a simple
// equirectangular projection, plus the projection constants so destination
// pins can be placed from their latitude/longitude.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const world = require('world-atlas/countries-10m.json')
const countries = feature(world, world.objects.countries)
const kenya = countries.features.find((f) => f.properties.name === 'Kenya')
if (!kenya) throw new Error('Kenya not found')

// bounds (lon/lat) with a margin
const B = { west: 33.7, east: 42.1, north: 5.2, south: -4.9 }
const W = 1000
const k = W / (B.east - B.west)
const H = Math.round((B.north - B.south) * k)
const x = (lon) => ((lon - B.west) * k).toFixed(1)
const y = (lat) => ((B.north - lat) * k).toFixed(1)
const rings = kenya.geometry.type === 'Polygon' ? [kenya.geometry.coordinates] : kenya.geometry.coordinates
const d = rings
  .flatMap((poly) => poly.map((ring) => 'M' + ring.map(([lo, la]) => `${x(lo)} ${y(la)}`).join('L') + 'Z'))
  .join('')
const out = `// Generated by scripts/geo/kenya.mjs from Natural Earth (public domain). Do not edit.
/* eslint-disable */
export const KENYA = { d: ${JSON.stringify(d)}, width: ${W}, height: ${H}, west: ${B.west}, north: ${B.north}, k: ${k} } as const
export const project = (lat: number, lng: number) => ({ x: (lng - KENYA.west) * KENYA.k, y: (KENYA.north - lat) * KENYA.k })
`
fs.mkdirSync('src/components/destinations', { recursive: true })
fs.writeFileSync('src/components/destinations/kenya.ts', out)
console.log('kenya path', d.length, 'chars,', W, 'x', H)
